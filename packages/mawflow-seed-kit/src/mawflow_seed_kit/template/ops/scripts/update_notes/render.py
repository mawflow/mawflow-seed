"""Deterministic rendering and explicit legacy changelog import."""

from __future__ import annotations

import hashlib
import html
import json
import os
import re
from pathlib import Path
from urllib.parse import quote

from .store import CLOUD, CATEGORIES, DELIVERY, VALIDATION, digest, safe_path, validate


def text(value: str) -> str:
    value = html.escape(value, quote=False)
    return re.sub(r"([\\`*_{}\[\]()#!|])", r"\\\1", value)


def render(
    root: Path,
    records: list[dict],
    output: str,
    limit: int | None,
    project_name: str,
    *,
    portable=False,
) -> bytes:
    selected = records if limit is None else records[:limit]
    mode = "全部" if limit is None else f"最近 {limit} 条"
    doc_key = "updates." + re.sub(
        r"[^a-z0-9]+", ".", output.removesuffix(".md").lower()
    ).strip(".")
    meta = [
        "---",
        f"doc_key: {doc_key}",
        "doc_type: release_notes",
        "stage: development",
        "status: active",
        "owner: project-owner",
        "tags: [updates, release-notes, generated]",
        "handbook:",
        "  visibility: project_private",
        "  sync:",
        "    enabled: true",
        "read_contract:",
        '  summary: "从任务级权威变更片段生成的项目更新动态；开发、发布和验收分别标注。"',
        '  ai_read_hint: "阅读更新动态时使用；修改回到 .maw/changes 权威片段。"',
        "---",
        "",
    ]
    lines = meta + [
        f"# {text(project_name)} 更新动态",
        "",
        f"> {mode}，展示 {len(selected)} 条，共 {len(records)} 条有效动态。",
        "> 权威来源：`.maw/changes/*.yaml`。本页可重建；历史补录未独立复验，状态以详情为准。",
        "",
        "<!-- generated by ops/scripts/generate-update-notes.py; edit source fragments -->",
        "",
    ]
    current_group = None
    replaced = {
        item["payload"]["supersedes"]
        for item in records
        if item["payload"].get("supersedes")
    }
    for item in selected:
        payload = item["payload"]
        group = (
            payload["occurred_at"][:10],
            payload.get("version") or "日常更新",
            payload["module_key"],
        )
        if current_group is None or current_group[:2] != group[:2]:
            lines += [f"## {group[0]} · {text(group[1])}", ""]
            current_group = None
        if current_group != group:
            lines += [f"### {text(payload['module_name'])}", ""]
        current_group = group
        important = "【重要】" if payload["importance"] == "important" else ""
        links = []
        for detail in payload["details"]:
            target = detail.get("url")
            if target is None:
                if portable:
                    links.append(f"来源：`{detail['path']}`")
                    continue
                target = quote(
                    os.path.relpath(
                        safe_path(root, detail["path"]), (root / output).parent
                    ).replace(os.sep, "/"),
                    safe="/.-_",
                )
            else:
                target = quote(target, safe=":/#%.-_~")
            links.append(f"[{text(detail['label'])}]({target})")
        correction = "已更正；" if item["record_key"] in replaced else ""
        lines += [
            f"- {important}{CATEGORIES[payload['category']]}：{text(payload['summary'])}（{correction}{DELIVERY[payload['delivery_state']]}；{VALIDATION[payload['validation_state']]}） {' '.join(links)} <!-- {item['record_key']} -->",
            "",
        ]
    if not selected:
        lines += ["暂无已记录动态。日常任务完成时追加权威片段后重新生成。", ""]
    return ("\n".join(lines).rstrip() + "\n").encode("utf-8")


def cloud_documents(
    root: Path, records: list[dict], project_name: str
) -> dict[str, bytes]:
    documents = {}
    months = {}
    for item in records:
        months.setdefault(item["payload"]["occurred_at"][:7], []).append(item)
    links = []
    for month, items in months.items():
        for index in range(0, len(items), 100):
            relative = f"docs/handbooks/release-ops/update-history/{month}-{index // 100 + 1:03}.md"
            content = render(
                root,
                items[index : index + 100],
                relative,
                None,
                project_name,
                portable=True,
            )
            documents[relative] = content
            links.append(
                f"- [{month} 第 {index // 100 + 1} 页（{len(items[index : index + 100])} 条）](update-history/{Path(relative).name})"
            )
    content = render(root, records, CLOUD, 100, project_name, portable=True).decode()
    marker = "<!-- generated by ops/scripts/generate-update-notes.py; edit source fragments -->"
    archive = (
        "\n\n## 完整历史目录\n\n"
        + "\n".join(links)
        + "\n\n> 本页及历史分页可经项目手册同步。仓库文件来源按原路径标注；云端不生成无法访问的本机详情链接。"
    )
    documents[CLOUD] = content.replace(marker, marker + archive).encode()
    if (
        any(len(content) > 512 * 1024 for content in documents.values())
        or sum(map(len, documents.values())) > 50 * 1024 * 1024
    ):
        raise ValueError("cloud_publication_budget_exceeded")
    directory = safe_path(root, "docs/handbooks/release-ops/update-history")
    if any(
        path.relative_to(root).as_posix() not in documents
        for path in directory.glob("*.md")
    ):
        raise ValueError("obsolete_cloud_page_requires_review")
    manifest = {
        "schema": "mawflow.update_notes.cloud_export.v1",
        "status": "prepared_not_published",
        "total": len(records),
        "source_fingerprint": digest(records),
        "pages": [
            {
                "path": path,
                "sha256": hashlib.sha256(content).hexdigest(),
                "size_bytes": len(content),
            }
            for path, content in documents.items()
        ],
    }
    documents[".maw/generated/update-notes-cloud.json"] = (
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    ).encode()
    return documents


def import_changelogs(root: Path, sources: list[str]) -> tuple[list[dict], list[str]]:
    items, warnings = [], []
    for source in sources:
        if not re.fullmatch(r"docs/changelogs/[a-z0-9-]+\.md", source):
            raise ValueError("import_source_must_be_module_changelog")
        path = safe_path(root, source)
        if path.stat().st_size > 1024 * 1024:
            raise ValueError("changelog_budget_exceeded")
        content = path.read_bytes()
        module = path.stem
        for number, line in enumerate(content.decode("utf-8").splitlines(), 1):
            if not re.match(r"^\|\s*\d{4}-\d{2}-\d{2}\s*\|", line):
                continue
            fields = split_table_row(line)
            if len(fields) != 7:
                warnings.append(f"unsupported_changelog_row:{source}:{number}")
                continue
            date, version, task, kind, summary, status, _ = fields
            if status != "confirmed":
                warnings.append("unconfirmed_changelog_row:" + source)
                continue
            tokens = kind.split("/")
            category = next(
                (
                    value
                    for legacy, value in (
                        ("fix", "fixed"),
                        ("security", "security"),
                        ("feature", "added"),
                        ("docs", "docs"),
                    )
                    if legacy in tokens
                ),
                "changed",
            )
            # The logical ID excludes file order and the source-file hash, so adding
            # another row does not create duplicates when a migration is retried.
            key = "history." + digest([module, date, version, task, summary])[:24]
            item = {
                "schema_version": 1,
                "record_key": key,
                "task_key": "historical-changelog-import",
                "record_type": "update_note",
                "operation": "append",
                "payload": {
                    "schema": "mawflow.update_note.v1",
                    "occurred_at": date + "T00:00:00+08:00",
                    "title": task or summary[:100],
                    "summary": summary,
                    "category": category,
                    "module_key": module,
                    "module_name": module,
                    "version": version or "历史更新",
                    "delivery_state": "historical",
                    "validation_state": "unverified",
                    "importance": "normal",
                    "audience": "project",
                    "details": [{"label": "历史来源", "path": source}],
                    "provenance": {
                        "kind": "module_changelog_table",
                        "source_path": source,
                        "source_sha256": hashlib.sha256(content).hexdigest(),
                    },
                },
                "evidence_refs": [{"path": source, "kind": "module_changelog"}],
            }
            try:
                validate(root, item)
            except ValueError as exc:
                warnings.append(f"import_row_rejected:{source}:{number}:{exc}")
                continue
            items.append(item)
    return items, sorted(set(warnings))


def split_table_row(line: str) -> list[str]:
    cells, cell, ticks = [], [], 0
    index = 0
    while index < len(line):
        char = line[index]
        if char == "\\" and index + 1 < len(line):
            cell.extend(line[index : index + 2])
            index += 2
            continue
        if char == "`":
            end = index + 1
            while end < len(line) and line[end] == "`":
                end += 1
            count = end - index
            ticks = count if not ticks else 0 if ticks == count else ticks
            cell.extend(line[index:end])
            index = end
            continue
        if char == "|" and not ticks:
            cells.append("".join(cell).strip())
            cell = []
        else:
            cell.append(char)
        index += 1
    cells.append("".join(cell).strip())
    return cells[1:-1]
